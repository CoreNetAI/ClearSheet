"use client";

import { useMemo, useState } from "react";
import Link from "next/link";
import { Download, Search } from "lucide-react";

import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { Card, CardContent } from "@/components/ui/card";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { InvoiceStatusBadge } from "@/components/status-badge";
import { Tip } from "@/components/ui/tooltip";
import { formatDate, formatMoney } from "@/lib/format";
import type { InvoiceStatus } from "@/lib/types";

export interface InvoiceRow {
  id: string;
  invoiceNumber: string;
  clientName: string;
  periodStart: string | null;
  periodEnd: string | null;
  total: number;
  status: InvoiceStatus;
  // Audit attribution (hidden until toggled on).
  generatedBy: string;
  reviewedBy: string;
  accountedBy: string;
}

export function InvoicesList({ invoices }: { invoices: InvoiceRow[] }) {
  const [search, setSearch] = useState("");
  const [status, setStatus] = useState<"all" | InvoiceStatus>("all");
  const [showAudit, setShowAudit] = useState(false);

  const filtered = useMemo(() => {
    const q = search.trim().toLowerCase();
    return invoices.filter((inv) => {
      if (status !== "all" && inv.status !== status) return false;
      if (!q) return true;
      return `${inv.invoiceNumber} ${inv.clientName}`
        .toLowerCase()
        .includes(q);
    });
  }, [invoices, search, status]);

  return (
    <div>
      <div className="mb-4 flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <Tip content="Type to filter invoices by invoice number or client name.">
            <div className="relative">
              <Search className="absolute left-2 top-2.5 h-4 w-4 text-muted-foreground" />
              <Input
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                placeholder="Search number or client…"
                className="w-48 pl-8 sm:w-64"
              />
            </div>
          </Tip>
          <Select
            value={status}
            onValueChange={(v) => setStatus(v as "all" | InvoiceStatus)}
          >
            <Tip content="Filter by lifecycle: Draft (new), Sent (issued to client), Paid (accounted), or Void.">
              <SelectTrigger className="w-32">
                <SelectValue />
              </SelectTrigger>
            </Tip>
            <SelectContent>
              <SelectItem value="all">All status</SelectItem>
              <SelectItem value="draft">Draft</SelectItem>
              <SelectItem value="sent">Sent</SelectItem>
              <SelectItem value="paid">Paid</SelectItem>
              <SelectItem value="void">Void</SelectItem>
            </SelectContent>
          </Select>
        </div>
        <div className="flex items-center gap-2">
          <Tip content="Reveal extra columns showing who generated, reviewed/approved, and accounted (marked paid) each invoice.">
            <Button
              variant={showAudit ? "default" : "outline"}
              onClick={() => setShowAudit((v) => !v)}
            >
              {showAudit ? "Hide audit" : "Show audit"}
            </Button>
          </Tip>
          <Tip content="Download all invoices — incl. deductions, reimbursements, net amount, and the audit trail — as an Excel file.">
            <Button
              variant="outline"
              onClick={() =>
                window.location.assign("/finance/invoices/export?format=xlsx")
              }
            >
              <Download className="h-4 w-4" />
              Export
            </Button>
          </Tip>
        </div>
      </div>

      <Card>
        <CardContent className="p-0">
          {filtered.length === 0 ? (
            <p className="p-10 text-center text-muted-foreground">
              {invoices.length === 0
                ? "No invoices yet. Generate one from Approved Hours."
                : "No invoices match your filter."}
            </p>
          ) : (
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Number</TableHead>
                  <TableHead>Client</TableHead>
                  <TableHead>Period</TableHead>
                  <TableHead className="text-right">Total</TableHead>
                  <TableHead>Status</TableHead>
                  {showAudit && (
                    <>
                      <TableHead>Generated by</TableHead>
                      <TableHead>Reviewed/approved by</TableHead>
                      <TableHead>Accounted by</TableHead>
                    </>
                  )}
                  <TableHead className="text-right" />
                </TableRow>
              </TableHeader>
              <TableBody>
                {filtered.map((inv) => (
                  <TableRow key={inv.id}>
                    <TableCell className="font-medium">
                      {inv.invoiceNumber}
                    </TableCell>
                    <TableCell>{inv.clientName || "—"}</TableCell>
                    <TableCell>
                      {formatDate(inv.periodStart)} – {formatDate(inv.periodEnd)}
                    </TableCell>
                    <TableCell className="text-right">
                      {formatMoney(inv.total)}
                    </TableCell>
                    <TableCell>
                      <InvoiceStatusBadge status={inv.status} />
                    </TableCell>
                    {showAudit && (
                      <>
                        <TableCell className="text-muted-foreground">
                          {inv.generatedBy || "—"}
                        </TableCell>
                        <TableCell className="text-muted-foreground">
                          {inv.reviewedBy || "—"}
                        </TableCell>
                        <TableCell className="text-muted-foreground">
                          {inv.accountedBy || "—"}
                        </TableCell>
                      </>
                    )}
                    <TableCell className="text-right">
                      <Button variant="ghost" size="sm" asChild>
                        <Link href={`/finance/invoices/${inv.id}`}>View</Link>
                      </Button>
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          )}
        </CardContent>
      </Card>
    </div>
  );
}
